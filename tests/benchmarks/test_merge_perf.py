"""Performance benchmarks for the merge pipeline.

Run with:
    pytest tests/benchmarks/ --benchmark-only --benchmark-save=baseline

These tests are skipped unless `--benchmark-only` is passed so the
default `pytest` invocation (used by the CI test suite) stays fast.

Each benchmark uses synthetic clips generated by the
`synthetic_clip_factory` fixture in conftest.py — no real user media.
"""
from __future__ import annotations

import os

import pytest


# Don't run these as part of the regular unit-test sweep; they take
# seconds-to-minutes each. The `--benchmark-only` flag from
# pytest-benchmark deselects everything not marked as a benchmark.
pytestmark = pytest.mark.benchmark


def _run_merge(merge_module, clips, output_path, **kwargs):
    return merge_module.merge_videos(
        clips,
        output_path,
        overwrite=True,
        **kwargs,
    )


@pytest.mark.parametrize('clip_count', [2, 5, 10])
def test_merge_throughput_baseline(
    benchmark, synthetic_clip_factory, merge_module, tmp_path, clip_count,
):
    """Baseline: merge N short clips, medium quality, no extra features.

    Captures the cost of normalize+concat alone, scaled with clip count.
    Output target: linear scaling — total time ≈ clip_count × per-clip.
    """
    clips = [synthetic_clip_factory(duration_sec=2.0) for _ in range(clip_count)]
    output = tmp_path / f'baseline_{clip_count}.mp4'

    def run():
        return _run_merge(merge_module, clips, str(output))

    success = benchmark.pedantic(run, rounds=1, iterations=1)
    assert success is True
    assert os.path.exists(output)


@pytest.mark.parametrize('quality', ['low', 'medium', 'high'])
def test_merge_quality_cost(
    benchmark, synthetic_clip_factory, merge_module, tmp_path, quality,
):
    """Quality preset cost. Verifies the low→high cost ratio is roughly
    bounded; `slow` x264 preset is expected to be ~3-5x ultrafast."""
    clips = [synthetic_clip_factory(duration_sec=2.0) for _ in range(3)]
    output = tmp_path / f'quality_{quality}.mp4'

    def run():
        return _run_merge(merge_module, clips, str(output), quality=quality)

    success = benchmark.pedantic(run, rounds=1, iterations=1)
    assert success is True


def test_merge_with_per_clip_edits(
    benchmark, synthetic_clip_factory, merge_module, tmp_path,
):
    """Phase 1 overhead: same merge with per-clip trim + color edits."""
    clips = [synthetic_clip_factory(duration_sec=3.0) for _ in range(3)]
    output = tmp_path / 'with_edits.mp4'
    clip_edits = [
        {'trimStart': 0.5, 'trimEnd': 0.5, 'brightness': 0.1},
        {'aspectRatio': '9:16', 'volume': 0.8},
        {'crop': {'x': 0, 'y': 0, 'width': 320, 'height': 240}},
    ]

    def run():
        return _run_merge(
            merge_module, clips, str(output), clip_edits=clip_edits,
        )

    success = benchmark.pedantic(run, rounds=1, iterations=1)
    assert success is True


